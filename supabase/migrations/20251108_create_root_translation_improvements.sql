-- Root Translation Improvements Table
-- Date: 2025-11-08
-- Purpose: Track reviewer suggestions for improved English translations and tashkeel at the root level

-- ============================================================================
-- HELPER FUNCTIONS
-- ============================================================================

-- Ensure set_updated_at helper exists (idempotent)
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = timezone('utc', now());
  RETURN NEW;
END;
$$;

-- ============================================================================
-- TABLE DEFINITION
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.root_translation_improvements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  root_id INTEGER NOT NULL REFERENCES public.roots(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending',
  suggested_english TEXT NOT NULL,
  suggested_tashkeel TEXT NOT NULL,
  reviewer_notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now())
);

-- Enable row level security to mirror translation_improvements table configuration
ALTER TABLE public.root_translation_improvements ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow all operations on root_translation_improvements"
ON public.root_translation_improvements
FOR ALL
TO public
USING (true)
WITH CHECK (true);

-- ============================================================================
-- INDEXES
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_root_translation_improvements_root_id
  ON public.root_translation_improvements(root_id);

CREATE INDEX IF NOT EXISTS idx_root_translation_improvements_status
  ON public.root_translation_improvements(status);

-- ============================================================================
-- TRIGGERS
-- ============================================================================

CREATE TRIGGER trg_root_translation_improvements_updated_at
BEFORE UPDATE ON public.root_translation_improvements
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();
