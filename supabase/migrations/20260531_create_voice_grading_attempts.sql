-- Voice Grading Attempts (telemetry)
-- Date: 2026-05-31
-- Purpose: Capture one row per RESOLVED on-device voice-grading attempt as a
--   labeled dataset for (1) building the self-learning accept-list, (2) tuning
--   matchSingleWord thresholds on real data, (3) finding mishear-prone words,
--   and (4) diagnosing capture quality.
--
-- SAFETY: ADDITIVE ONLY. New table + its own RLS + indexes. Touches no existing
--   schema, so apps currently running in production are unaffected — they never
--   query this table; only new OTA code writes to it.

CREATE TABLE IF NOT EXISTS public.voice_grading_attempts (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now()),
  root_id       INTEGER REFERENCES public.roots(id) ON DELETE SET NULL,

  -- Grading signal (the core label lives in matched + resolution)
  expected           TEXT,            -- normalized expected meaning
  transcript         TEXT,            -- raw Parakeet output (trimmed)
  normalized_spoken  TEXT,            -- normalized transcript
  matched            BOOLEAN NOT NULL,
  match_method       TEXT,            -- which matchSingleWord branch fired
  similarity         REAL,
  suggestion         TEXT,            -- panel nudge: 'unknown' | 'retry' | null
  resolution         TEXT NOT NULL,   -- 'auto_known' | 'accept' | 'reject' | 'retry'
  attempt_index      INTEGER NOT NULL DEFAULT 0, -- retries within the same card

  -- Recorder diagnostics (correlate mishears with capture quality)
  duration_ms        INTEGER,
  stop_reason        TEXT,            -- 'silence' | 'noSpeech' | 'maxDuration' | 'watchdog' | 'manual'
  heard_speech       BOOLEAN,
  peak_rms           REAL,
  buffer_count       INTEGER,
  first_buffer_ms    INTEGER,
  stop_decided_at_ms INTEGER,

  -- Segmentation
  model_id     TEXT,
  platform     TEXT,
  app_version  TEXT,

  -- Local developer / advanced settings snapshot + effective capture config +
  -- decoding config + room for future experiment flags. JSONB so new recording
  -- knobs never require a migration. Example shape:
  --   {
  --     "settings": { "energyGateEnabled": true, "gainNormalizeEnabled": true,
  --                   "iosRawMode": false, "debugEnabled": false },
  --     "recordingConfig": { "speechFactor": 1.5, "silenceHangMs": 900,
  --                          "maxDurationMs": 15000, "noSpeechTimeoutMs": 8000, ... },
  --     "decoding": { "method": "modified_beam_search", "maxActivePaths": 8 }
  --   }
  meta         JSONB NOT NULL DEFAULT '{}'::jsonb
);

ALTER TABLE public.voice_grading_attempts ENABLE ROW LEVEL SECURITY;

-- Authenticated users may insert only their own attempts.
-- (DROP-then-CREATE so the whole migration is safely re-runnable.)
DROP POLICY IF EXISTS "voice_grading_attempts_insert_own" ON public.voice_grading_attempts;
CREATE POLICY "voice_grading_attempts_insert_own"
  ON public.voice_grading_attempts
  FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);

-- Authenticated users may read only their own attempts.
-- (Analysis/aggregation is done with the service role, which bypasses RLS.)
DROP POLICY IF EXISTS "voice_grading_attempts_select_own" ON public.voice_grading_attempts;
CREATE POLICY "voice_grading_attempts_select_own"
  ON public.voice_grading_attempts
  FOR SELECT TO authenticated
  USING (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS idx_voice_grading_attempts_user_id
  ON public.voice_grading_attempts(user_id);
CREATE INDEX IF NOT EXISTS idx_voice_grading_attempts_root_id
  ON public.voice_grading_attempts(root_id);
CREATE INDEX IF NOT EXISTS idx_voice_grading_attempts_created_at
  ON public.voice_grading_attempts(created_at);
-- Fast slice for the highest-value query: false negatives (matched=false, resolution='accept').
CREATE INDEX IF NOT EXISTS idx_voice_grading_attempts_label
  ON public.voice_grading_attempts(matched, resolution);
-- Flexible querying of dev settings / experiment flags,
-- e.g. WHERE meta @> '{"settings":{"iosRawMode":true}}'.
CREATE INDEX IF NOT EXISTS idx_voice_grading_attempts_meta
  ON public.voice_grading_attempts USING GIN (meta);
