#!/usr/bin/env npx tsx
/**
 * Step 4: Merge labeled batch files into a single fixture + summary stats.
 *
 * Reads scripts/output/eval-corpus.labeled.batch-*.jsonl
 * Produces:
 *   - scripts/output/eval-corpus.labeled.merged.json — full merged corpus with metadata
 *   - __tests__/fixtures/grammarGroundTruth.db.ts — GroundTruthCase[] fixture loadable by the benchmark
 *   - scripts/output/eval-corpus.labeled.stats.json — disagreement breakdown by bucket / type
 *
 * The new fixture is intentionally separate from grammarGroundTruth.ts (the 67 hand-verified cases)
 * so reviewers can tell at a glance which cases are LLM-labeled vs. human-verified.
 *
 * Run with: npx tsx scripts/merge-labeled-corpus.ts [--min-confidence=70] [--split=70]
 */

import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ARG = (name: string) =>
  process.argv.find(a => a.startsWith(`--${name}`))?.split('=')[1] ?? null;
const MIN_CONFIDENCE = ARG('min-confidence') ? parseInt(ARG('min-confidence')!, 10) : 70;
const TRAIN_PCT = ARG('split') ? parseInt(ARG('split')!, 10) : 70;

interface LabeledLine {
  arabic: string;
  english: string;
  bucket: string;
  label: {
    expectedPrefixes: string[];
    expectedSuffix: string | null;
    expectedInfix: string | null;
    expectedHasComponents: boolean;
    confidence: number;
    reasoning: string;
  };
  currentAnalysis: {
    hasComponents: boolean;
    prefixes: string[];
    suffix: string | null;
    infix: string | null;
    diacritic: string | null;
    remainingArabic: string;
  };
  agreesWithAnalyzer: boolean;
  disagreementType: string | null;
}

function readAllBatches(dir: string): LabeledLine[] {
  const files = fs
    .readdirSync(dir)
    .filter(f => f.startsWith('eval-corpus.labeled.batch-') && f.endsWith('.jsonl'))
    .sort();
  const all: LabeledLine[] = [];
  for (const f of files) {
    const lines = fs.readFileSync(path.join(dir, f), 'utf-8').split('\n').filter(Boolean);
    for (const line of lines) {
      try {
        all.push(JSON.parse(line));
      } catch (e) {
        console.error(`  Bad line in ${f}: ${line.slice(0, 100)}`);
      }
    }
    console.log(`  ${f}: ${lines.length} entries`);
  }
  return all;
}

function dedupeByKey(rows: LabeledLine[]): LabeledLine[] {
  const map = new Map<string, LabeledLine>();
  for (const r of rows) {
    const k = `${r.arabic}|${r.english}`;
    if (!map.has(k)) map.set(k, r);
  }
  return Array.from(map.values());
}

function categoryFor(
  label: LabeledLine['label'],
): 'prefix' | 'suffix' | 'infix' | 'combined' | 'none' {
  const hasPre = label.expectedPrefixes.length > 0;
  const hasSuf = !!label.expectedSuffix;
  const hasInf = !!label.expectedInfix;
  const componentCount = (hasPre ? 1 : 0) + (hasSuf ? 1 : 0) + (hasInf ? 1 : 0);
  if (componentCount === 0) return 'none';
  if (componentCount > 1) return 'combined';
  if (hasPre) return 'prefix';
  if (hasSuf) return 'suffix';
  return 'infix';
}

interface GroundTruthCase {
  arabic: string;
  english: string;
  expectedPrefixes: string[];
  expectedSuffix: string | null;
  expectedInfix?: string | null;
  expectedHasComponents: boolean;
  category: 'prefix' | 'suffix' | 'infix' | 'combined' | 'none';
  source: 'database';
  confidence: number;
  bucket: string;
  reasoning: string;
}

function toGroundTruth(rows: LabeledLine[]): GroundTruthCase[] {
  return rows.map(r => ({
    arabic: r.arabic,
    english: r.english,
    expectedPrefixes: r.label.expectedPrefixes,
    expectedSuffix: r.label.expectedSuffix,
    expectedInfix: r.label.expectedInfix,
    expectedHasComponents: r.label.expectedHasComponents,
    category: categoryFor(r.label),
    source: 'database' as const,
    confidence: r.label.confidence,
    bucket: r.bucket,
    reasoning: r.label.reasoning,
  }));
}

function deterministicSplit<T>(arr: T[], trainPct: number): { train: T[]; test: T[] } {
  // Hash-based deterministic split — same input always yields same split
  const train: T[] = [];
  const test: T[] = [];
  for (const item of arr) {
    const json = JSON.stringify(item);
    let hash = 0;
    for (let i = 0; i < json.length; i++) hash = (hash * 31 + json.charCodeAt(i)) >>> 0;
    if (hash % 100 < trainPct) train.push(item);
    else test.push(item);
  }
  return { train, test };
}

function writeFixtureTs(outPath: string, train: GroundTruthCase[], test: GroundTruthCase[]) {
  const header = `/**
 * LLM-labeled ground truth from real database words.
 *
 * Generated by scripts/merge-labeled-corpus.ts. DO NOT edit by hand —
 * to regenerate, re-run the labeling pipeline (scripts/label-eval-corpus +
 * merge-labeled-corpus). For hand-verified cases, see grammarGroundTruth.ts.
 *
 * Each case includes:
 *   - confidence: LLM confidence (0-100); cases below threshold are excluded at merge time
 *   - bucket: which sampling bucket the case came from
 *   - reasoning: short linguistic justification from the labeler
 *
 * Train/test split is deterministic (hash-based on case content).
 */
import type { GroundTruthCase } from '@/utils/benchmarkUtils';

interface DbGroundTruthCase extends GroundTruthCase {
  confidence: number;
  bucket: string;
  reasoning: string;
}

`;
  const trainLit = JSON.stringify(train, null, 2);
  const testLit = JSON.stringify(test, null, 2);
  const body = `export const DB_TRAIN_CASES: DbGroundTruthCase[] = ${trainLit};\n\nexport const DB_TEST_CASES: DbGroundTruthCase[] = ${testLit};\n\nexport const ALL_DB_CASES: DbGroundTruthCase[] = [...DB_TRAIN_CASES, ...DB_TEST_CASES];\n`;
  fs.writeFileSync(outPath, header + body);
}

function statsFor(rows: LabeledLine[]) {
  const byBucket: Record<string, { count: number; disagreements: number }> = {};
  const byDisagreement: Record<string, number> = {};
  let totalConfidence = 0;
  for (const r of rows) {
    byBucket[r.bucket] = byBucket[r.bucket] || { count: 0, disagreements: 0 };
    byBucket[r.bucket]!.count++;
    if (!r.agreesWithAnalyzer) byBucket[r.bucket]!.disagreements++;
    const dt = r.disagreementType ?? 'agree';
    byDisagreement[dt] = (byDisagreement[dt] ?? 0) + 1;
    totalConfidence += r.label.confidence;
  }
  return {
    total: rows.length,
    avgConfidence: totalConfidence / Math.max(rows.length, 1),
    byBucket,
    byDisagreement,
  };
}

function main() {
  const outDir = path.join(__dirname, 'output');
  console.log('Reading batch files…');
  const all = readAllBatches(outDir);
  console.log(`Total raw labeled lines: ${all.length}`);

  const deduped = dedupeByKey(all);
  console.log(`After dedup: ${deduped.length}`);

  const filtered = deduped.filter(r => r.label.confidence >= MIN_CONFIDENCE);
  const dropped = deduped.length - filtered.length;
  console.log(
    `Dropped ${dropped} low-confidence (<${MIN_CONFIDENCE}) entries → ${filtered.length} kept.`,
  );

  const groundTruth = toGroundTruth(filtered);
  const { train, test } = deterministicSplit(groundTruth, TRAIN_PCT);
  console.log(`Split (deterministic): train=${train.length} test=${test.length}`);

  const stats = statsFor(filtered);
  console.log(`\nStats:`);
  console.log(`  avg confidence: ${stats.avgConfidence.toFixed(1)}`);
  console.log(`  disagreement types: ${JSON.stringify(stats.byDisagreement)}`);
  console.log(`  by bucket:`);
  for (const [b, v] of Object.entries(stats.byBucket)) {
    console.log(
      `    ${b}: ${v.count} cases, ${v.disagreements} disagreements (${((v.disagreements / v.count) * 100).toFixed(1)}%)`,
    );
  }

  // Write outputs
  const mergedPath = path.join(outDir, 'eval-corpus.labeled.merged.json');
  fs.writeFileSync(
    mergedPath,
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        totalLabeled: filtered.length,
        droppedLowConfidence: dropped,
        minConfidence: MIN_CONFIDENCE,
        trainPct: TRAIN_PCT,
        stats,
        entries: filtered,
      },
      null,
      2,
    ),
  );
  console.log(`\nWrote ${mergedPath}`);

  const statsPath = path.join(outDir, 'eval-corpus.labeled.stats.json');
  fs.writeFileSync(statsPath, JSON.stringify(stats, null, 2));
  console.log(`Wrote ${statsPath}`);

  const fixturePath = path.join(__dirname, '../__tests__/fixtures/grammarGroundTruth.db.ts');
  writeFixtureTs(fixturePath, train, test);
  console.log(`Wrote ${fixturePath} (${train.length} train + ${test.length} test cases)`);
}

main();
